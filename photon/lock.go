package photon

import (
	"fmt"
	"sort"
	"strings"
)

// LockEntry is a resolved dependency pinned to an exact commit.
type LockEntry struct {
	Name   string // dependency name in the manifest
	Source string // the spec as written in the manifest
	Ref    string // requested tag/branch/commit ("" for default)
	Commit string // the exact commit hash that was fetched
}

// Lock is the parsed photon.lock.
type Lock struct {
	Entries []LockEntry
}

// Get returns the entry for name.
func (l *Lock) Get(name string) (LockEntry, bool) {
	for _, e := range l.Entries {
		if e.Name == name {
			return e, true
		}
	}
	return LockEntry{}, false
}

// Set adds or replaces an entry.
func (l *Lock) Set(e LockEntry) {
	for i := range l.Entries {
		if l.Entries[i].Name == e.Name {
			l.Entries[i] = e
			return
		}
	}
	l.Entries = append(l.Entries, e)
}

// ParseLock parses a photon.lock.
func ParseLock(data string) (*Lock, error) {
	l := &Lock{}
	var cur *LockEntry
	flush := func() {
		if cur != nil && cur.Name != "" {
			l.Entries = append(l.Entries, *cur)
		}
		cur = nil
	}
	for _, raw := range strings.Split(data, "\n") {
		line := strings.TrimSpace(stripComment(raw))
		if line == "" {
			continue
		}
		if line == "[[package]]" {
			flush()
			cur = &LockEntry{}
			continue
		}
		if cur == nil {
			continue
		}
		key, val, ok := splitKeyValue(line)
		if !ok {
			continue
		}
		s, err := parseString(strings.TrimSpace(val))
		if err != nil {
			continue
		}
		switch strings.TrimSpace(key) {
		case "name":
			cur.Name = s
		case "source":
			cur.Source = s
		case "ref":
			cur.Ref = s
		case "commit":
			cur.Commit = s
		}
	}
	flush()
	return l, nil
}

// Encode renders the lockfile.
func (l *Lock) Encode() string {
	var b strings.Builder
	b.WriteString("# photon.lock - generated by photon; do not edit by hand\n")
	entries := append([]LockEntry(nil), l.Entries...)
	sort.SliceStable(entries, func(i, j int) bool { return entries[i].Name < entries[j].Name })
	for _, e := range entries {
		b.WriteString("\n[[package]]\n")
		fmt.Fprintf(&b, "name = %q\n", e.Name)
		fmt.Fprintf(&b, "source = %q\n", e.Source)
		fmt.Fprintf(&b, "ref = %q\n", e.Ref)
		fmt.Fprintf(&b, "commit = %q\n", e.Commit)
	}
	return b.String()
}

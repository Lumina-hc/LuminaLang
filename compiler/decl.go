package compiler

import (
	"fmt"
	"strings"
)

// WriteDecl renders a module's public signatures as a .lumi declaration file.
func WriteDecl(module string, funcs []lumcFunc) string {
	var b strings.Builder
	fmt.Fprintf(&b, "// %s.lumi - generated by LuminaLang; declarations only.\n", module)
	fmt.Fprintf(&b, "module %s\n", module)
	for _, f := range funcs {
		params := make([]string, len(f.Params))
		for i, p := range f.Params {
			params[i] = p.Name + ": " + p.Type
		}
		fmt.Fprintf(&b, "fn %s(%s) %s\n", f.Name, strings.Join(params, ", "), f.Ret)
	}
	return b.String()
}

// ParseDecl parses a .lumi declaration file, returning the module name and the
// declared functions.
func ParseDecl(data string) (string, []lumcFunc, error) {
	module := ""
	var funcs []lumcFunc
	for i, raw := range strings.Split(data, "\n") {
		line := raw
		if idx := strings.Index(line, "//"); idx >= 0 {
			line = line[:idx]
		}
		line = strings.TrimSpace(line)
		if line == "" {
			continue
		}
		switch {
		case strings.HasPrefix(line, "module "):
			module = strings.TrimSpace(strings.TrimPrefix(line, "module "))
		case strings.HasPrefix(line, "fn "):
			f, err := parseDeclFn(strings.TrimSpace(line[len("fn "):]))
			if err != nil {
				return "", nil, fmt.Errorf("%d: %v", i+1, err)
			}
			funcs = append(funcs, f)
		default:
			return "", nil, fmt.Errorf("%d: unexpected %q", i+1, line)
		}
	}
	return module, funcs, nil
}

func parseDeclFn(s string) (lumcFunc, error) {
	open := strings.IndexByte(s, '(')
	close := strings.LastIndexByte(s, ')')
	if open < 0 || close < open {
		return lumcFunc{}, fmt.Errorf("expected 'name(params) ret', got %q", s)
	}
	name := strings.TrimSpace(s[:open])
	if name == "" {
		return lumcFunc{}, fmt.Errorf("missing function name in %q", s)
	}
	f := lumcFunc{Name: name, Ret: strings.TrimSpace(s[close+1:])}
	params := strings.TrimSpace(s[open+1 : close])
	if params != "" {
		for _, part := range strings.Split(params, ",") {
			part = strings.TrimSpace(part)
			colon := strings.IndexByte(part, ':')
			if colon < 0 {
				return lumcFunc{}, fmt.Errorf("expected 'name: type', got %q", part)
			}
			f.Params = append(f.Params, lumcParam{
				Name: strings.TrimSpace(part[:colon]),
				Type: strings.TrimSpace(part[colon+1:]),
			})
		}
	}
	return f, nil
}
